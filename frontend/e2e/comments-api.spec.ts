import { expect, test } from './test'
import { mockPlayers, signedInPreview } from './community-fixture'

test.beforeEach(async ({ page }) => { await signedInPreview(page); await mockPlayers(page) })

test('comment mutations wait for the API and preserve drafts and content on failure', async ({ page }, info) => {
  let writes = 0
  let release!: () => void
  const pending = new Promise<void>(resolve => { release = resolve })
  await page.route(/\/api\/posts\/\d+\/comments$/, async route => {
    if (route.request().method() !== 'POST') return route.fallback()
    writes++
    expect(route.request().postDataJSON()).toEqual({ body: '서버에 남길 댓글', parentId: null })
    if (writes === 1) return route.fulfill({ status: 500, json: {} })
    await pending
    return route.fallback()
  })
  await page.goto('/community')
  const post = page.getByRole('article').first()
  await post.getByRole('button', { name: /^댓글 \d+개$/ }).click()
  const input = post.getByRole('textbox', { name: '댓글 입력' })
  await input.fill('서버에 남길 댓글')
  await post.getByRole('button', { name: /^댓글 \d+개$/ }).click()
  await expect(input).toBeHidden()
  await post.getByRole('button', { name: /^댓글 \d+개$/ }).click()
  await expect(input).toHaveValue('서버에 남길 댓글')
  await post.getByRole('button', { name: '댓글 등록', exact: true }).click()
  await expect(post.getByRole('alert')).toContainText('댓글을 저장하지 못했어요')
  await expect(input).toHaveValue('서버에 남길 댓글')
  await post.getByRole('button', { name: '댓글 등록', exact: true }).click()
  await expect(input).toBeDisabled()
  await expect(post.getByRole('button', { name: /댓글 등록$/ })).toBeDisabled()
  await expect(post.getByRole('button', { name: /댓글 등록$/ })).toHaveAttribute('data-loading')
  release()
  await expect(post.locator('.comment-body')).toHaveText('서버에 남길 댓글')
  await expect(post.getByRole('button', { name: '댓글 1개', exact: true })).toBeVisible()
  await expect(input).toHaveValue('')
  await post.locator('.post-comments').screenshot({ path: info.outputPath('comments-panel-desktop.png') })
  expect(writes).toBe(2)

  let failEdit = true
  let failDelete = true
  await page.route(/\/api\/posts\/\d+\/comments\/\d+$/, route => {
    if (route.request().method() === 'PUT' && failEdit) return route.fulfill({ status: 500, json: {} })
    if (route.request().method() === 'DELETE' && failDelete) return route.fulfill({ status: 500, json: {} })
    return route.fallback()
  })
  await post.getByRole('button', { name: '댓글 더보기', exact: true }).click()
  await page.getByRole('menuitem', { name: '댓글 수정', exact: true }).click()
  await post.getByRole('textbox', { name: '댓글 수정' }).fill('보존할 수정 내용')
  await post.getByRole('button', { name: '수정 완료', exact: true }).click()
  await expect(post.getByRole('alert')).toContainText('댓글을 저장하지 못했어요')
  await expect(post.getByRole('textbox', { name: '댓글 수정' })).toHaveValue('보존할 수정 내용')
  failEdit = false
  await post.getByRole('button', { name: '수정 완료', exact: true }).click()
  await expect(post.locator('.comment-body')).toHaveText('보존할 수정 내용')
  await expect(post.getByRole('button', { name: '댓글 더보기', exact: true })).toBeFocused()
  await post.getByRole('button', { name: '댓글 더보기', exact: true }).click()
  await page.getByRole('menuitem', { name: '댓글 삭제', exact: true }).click()
  const deleteDialog = page.getByRole('alertdialog', { name: '댓글을 삭제할까요?' })
  await deleteDialog.getByRole('button', { name: '취소', exact: true }).click()
  await expect(post.getByRole('button', { name: '댓글 더보기', exact: true })).toBeFocused()
  await post.getByRole('button', { name: '댓글 더보기', exact: true }).click()
  await page.getByRole('menuitem', { name: '댓글 삭제', exact: true }).click()
  await deleteDialog.getByRole('button', { name: '삭제 확인', exact: true }).click()
  await expect(deleteDialog.getByRole('alert')).toContainText('댓글을 삭제하지 못했어요')
  await deleteDialog.getByRole('button', { name: '취소', exact: true }).click()
  await expect(post.locator('.comment-body')).toHaveText('보존할 수정 내용')
  failDelete = false
  await post.getByRole('button', { name: '댓글 더보기', exact: true }).click()
  await page.getByRole('menuitem', { name: '댓글 삭제', exact: true }).click()
  await deleteDialog.getByRole('button', { name: '삭제 확인', exact: true }).click()
  await expect(deleteDialog).toHaveCount(0)
  await expect(post.getByText('삭제된 댓글입니다.')).toBeVisible()
  await expect(post.getByRole('button', { name: '댓글 0개', exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('community-preview'))).toBeNull()
})

test('comment, reply and edit drafts survive form switches and restore focus when closed', async ({ page }) => {
  await page.goto('/community')
  const post = page.getByRole('article').first()
  const toggle = post.getByRole('button', { name: /^댓글 \d+개$/ })
  await toggle.click()
  const input = post.getByRole('textbox', { name: '댓글 입력' })
  await expect(input).toHaveAttribute('maxlength', '500')
  expect(await input.evaluate(element => element.getBoundingClientRect().height)).toBeGreaterThanOrEqual(95)
  for (const body of ['원댓글 하나', '원댓글 둘']) {
    await input.fill(body)
    await post.getByRole('button', { name: '댓글 등록', exact: true }).click()
    await expect(input).toHaveValue('')
  }
  const roots = post.locator('.comment-list > .post-comment')
  await expect(roots).toHaveCount(2)
  const firstComment = roots.nth(1)
  const secondComment = roots.nth(0)
  const firstReply = firstComment.getByRole('button', { name: '답글', exact: true })
  const secondReply = secondComment.getByRole('button', { name: '답글', exact: true })
  const firstMore = firstComment.getByRole('button', { name: '댓글 더보기', exact: true }).first()
  const editFirst = async () => {
    await firstMore.click()
    await page.getByRole('menuitem', { name: '댓글 수정', exact: true }).click()
  }
  const replyInput = post.getByRole('textbox', { name: /에게 답글$/ })
  const editInput = post.getByRole('textbox', { name: '댓글 수정', exact: true })
  await input.fill('새 댓글 초안')
  await firstReply.click()
  await expect(replyInput).toBeFocused()
  await replyInput.fill('첫 답글 초안')
  await toggle.click()
  await toggle.click()
  await expect(replyInput).toHaveValue('첫 답글 초안')
  await expect(input).toHaveValue('새 댓글 초안')
  await editFirst()
  await expect(editInput).toBeFocused()
  await editInput.fill(' 첫 수정 초안 ')
  await secondReply.click()
  await replyInput.fill('두번째 답글 초안')
  await firstReply.click()
  await expect(replyInput).toHaveValue('첫 답글 초안')
  await editFirst()
  await expect(editInput).toHaveValue(' 첫 수정 초안 ')
  await firstComment.getByRole('button', { name: '취소', exact: true }).click()
  await expect(firstMore).toBeFocused()
  await editFirst()
  await expect(editInput).toHaveValue(' 첫 수정 초안 ')
  await post.getByRole('button', { name: '수정 완료', exact: true }).click()
  await expect(firstMore).toBeFocused()
  await expect(firstComment.locator('.comment-body')).toHaveText('첫 수정 초안')
  await editFirst()
  await expect(editInput).toHaveValue('첫 수정 초안')
  await firstComment.getByRole('button', { name: '취소', exact: true }).click()
  await firstReply.click()
  await expect(replyInput).toHaveValue('첫 답글 초안')
  await firstComment.getByRole('button', { name: '취소', exact: true }).click()
  await expect(firstReply).toBeFocused()
  await firstReply.click()
  await expect(replyInput).toHaveValue('첫 답글 초안')
  let failReply = true
  await page.route(/\/api\/posts\/\d+\/comments$/, route => {
    if (route.request().method() === 'POST' && failReply) return route.fulfill({ status: 500, json: {} })
    return route.fallback()
  })
  await post.getByRole('button', { name: '답글 등록', exact: true }).click()
  await expect(firstComment.getByRole('alert')).toContainText('댓글을 저장하지 못했어요')
  await expect(replyInput).toHaveValue('첫 답글 초안')
  failReply = false
  await post.getByRole('button', { name: '답글 등록', exact: true }).click()
  await expect(firstReply).toBeFocused()
  await expect(firstComment.locator('.comment-replies .comment-body')).toHaveText('첫 답글 초안')
  await firstReply.click()
  await expect(replyInput).toHaveValue('')
  await firstComment.getByRole('button', { name: '취소', exact: true }).click()
  await secondReply.click()
  await expect(replyInput).toHaveValue('두번째 답글 초안')
  await secondComment.getByRole('button', { name: '취소', exact: true }).click()
  await expect(secondReply).toBeFocused()
  await expect(input).toHaveValue('새 댓글 초안')
})

test('comments load only when opened, distinguish failure and empty, and paginate whole threads', async ({ page }) => {
  let reads = 0
  let mode = 'error'
  await page.route(/\/api\/posts\/\d+\/comments\?/, route => {
    reads++
    if (mode === 'error') return route.fulfill({ status: 500, json: {} })
    const pageNo = Number(new URL(route.request().url()).searchParams.get('page'))
    const root = { id: String(pageNo + 1), postId: '1', parentId: null, author: '다른 작성자', avatarSlug: null, body: `원댓글 ${pageNo + 1}`, createdAt: '2026-10-08T00:00:00Z', own: false, deleted: false }
    return route.fulfill({ json: { items: mode === 'empty' ? [] : [root, { ...root, id: String(pageNo + 100), parentId: root.id, body: `답글 ${pageNo + 1}` }], page: pageNo, hasMore: mode === 'pages' && pageNo === 0 } })
  })
  await page.goto('/community')
  const post = page.getByRole('article').first()
  await expect(post).toBeVisible()
  expect(reads).toBe(0)
  await post.getByRole('button', { name: /^댓글 \d+개$/ }).click()
  await expect(post.getByRole('alert')).toContainText('댓글을 불러오지 못했어요')
  await expect(post.getByText('첫 댓글을 남겨보세요.')).toHaveCount(0)
  mode = 'empty'
  await post.getByRole('button', { name: '댓글 다시 불러오기' }).click()
  await expect(post.getByText('첫 댓글을 남겨보세요.')).toBeVisible()
  mode = 'pages'
  await page.reload()
  await post.getByRole('button', { name: /^댓글 \d+개$/ }).click()
  await expect(post.locator('.comment-replies').first()).toContainText('답글 1')
  await post.getByRole('button', { name: '댓글 더 보기' }).click()
  await expect(post.locator('.comment-list > .post-comment')).toHaveCount(2)
  await expect(post.locator('.comment-replies').last()).toContainText('답글 2')
  await expect(post.getByRole('button', { name: '댓글 더 보기' })).toHaveCount(0)
  await expect(post.getByRole('button', { name: '댓글 더보기', exact: true })).toHaveCount(0)
})
