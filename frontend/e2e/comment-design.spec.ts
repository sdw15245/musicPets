import { expect, test } from './test'
import { mockPlayers, signedInPreview } from './community-fixture'

for (const width of [1440, 390]) {
  test(`comment menu, reply target and reading layout at ${width}px`, async ({ page }, info) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.setViewportSize({ width, height: 1000 })
    await signedInPreview(page)
    await mockPlayers(page)
    await page.goto('/community')
    const post = page.getByRole('article').first()
    await post.getByRole('button', { name: /^댓글 \d+개$/ }).click()
    const input = post.getByRole('textbox', { name: '댓글 입력' })
    await input.fill('늦은 저녁에 듣기 좋은 곡이네요. 기타 소리가 특히 좋아요.')
    await post.getByRole('button', { name: '댓글 등록', exact: true }).click()
    const root = post.locator('.comment-list > .post-comment').first()
    const more = root.getByRole('button', { name: '댓글 더보기', exact: true }).first()
    await expect(more).toBeVisible()
    await expect(root.getByRole('button', { name: '댓글 수정', exact: true })).toHaveCount(0)
    await more.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('menuitem', { name: '댓글 수정', exact: true })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(more).toBeFocused()
    await more.click()
    await page.getByRole('menu').screenshot({ path: info.outputPath(`comment-menu-${width}.png`) })
    await page.getByRole('menuitem', { name: '댓글 수정', exact: true }).click()
    await expect(root.getByRole('textbox', { name: '댓글 수정' })).toBeFocused()
    await root.getByRole('button', { name: '취소', exact: true }).click()
    await expect(more).toBeFocused()
    await more.click()
    await page.getByRole('menuitem', { name: '댓글 삭제', exact: true }).click()
    await page.getByRole('alertdialog').getByRole('button', { name: '취소', exact: true }).click()
    await expect(more).toBeFocused()
    await root.getByRole('button', { name: '답글', exact: true }).click()
    const replyInput = root.getByRole('textbox', { name: /에게 답글$/ })
    await expect(replyInput).toBeFocused()
    await replyInput.fill('저도요! 같은 앨범의 다른 곡도 들어보세요.')
    await root.getByRole('button', { name: '답글 등록', exact: true }).click()
    await expect(root.locator('.comment-replies .comment-body')).toHaveText('저도요! 같은 앨범의 다른 곡도 들어보세요.')
    await expect(root.locator('.comment-reply-target')).toContainText('에게 답글')
    await post.locator('.post-comments').screenshot({ path: info.outputPath(`comments-reading-${width}.png`) })
    await root.getByRole('button', { name: '답글', exact: true }).click()
    await replyInput.fill('다음에 들을 곡도 찾아볼게요.')
    await expect(replyInput).toHaveValue('다음에 들을 곡도 찾아볼게요.')
    const form = await root.locator('.comment-reply-form').boundingBox()
    const replies = await root.locator('.comment-replies').boundingBox()
    expect(form!.y + form!.height).toBeLessThanOrEqual(replies!.y)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await post.locator('.post-comments').screenshot({ path: info.outputPath(`comments-${width}.png`) })
    await root.getByRole('button', { name: '답글', exact: true }).click()
    await expect(replyInput).toBeHidden()
    await root.getByRole('button', { name: '답글', exact: true }).click()
    await expect(replyInput).toHaveValue('다음에 들을 곡도 찾아볼게요.')
    await expect(replyInput).toBeFocused()
    expect(errors).toEqual([])
  })
}
