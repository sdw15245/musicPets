test('guests can search captions and tags, recover from empty results and clear the search', async ({ page }, info) => {
  await mockPlayers(page)
  await page.setViewportSize({ width: 1440, height: 1000 })
  const queries: string[] = []
  page.on('request', request => {
    const url = new URL(request.url())
    if (url.pathname === '/api/posts') queries.push(url.searchParams.get('q') ?? '')
  })
  await page.goto('/community')
  const posts = page.getByRole('article')
  const input = page.getByRole('textbox', { name: '본문 또는 태그 검색' })
  const search = page.getByRole('button', { name: '게시글 검색', exact: true })
  await expect(posts).toHaveCount(5)
  const inputBounds = await input.boundingBox()
  const sortBounds = await page.getByRole('button', { name: '정렬: 최신글', exact: true }).boundingBox()
  expect(inputBounds!.x + inputBounds!.width).toBeLessThan(sortBounds!.x)
  expect(Math.abs(inputBounds!.y - sortBounds!.y)).toBeLessThan(15)
  await input.fill('출근길')
  await input.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true })
  expect(queries).toEqual([''])
  await input.press('Enter')
  await expect(posts).toHaveCount(1)
  await expect(posts).toContainText('유월')
  await input.fill('#산책')
  await search.click()
  await expect(posts).toHaveCount(2)
  await expect(page.getByRole('status')).toContainText('‘산책’ 검색 결과')
  await page.screenshot({ path: info.outputPath('post-search-desktop.png') })
  await input.fill('차분한')
  await input.press('Enter')
  await expect(posts).toHaveCount(1)
  await expect(posts).toContainText('느린오후')
  await input.fill('없는검색어')
  await search.click()
  await expect(page.getByText('검색 결과가 없어요', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '검색어 지우기', exact: true }).click()
  await expect(posts).toHaveCount(5)
  await expect(input).toHaveValue('')
  await expect(input).toBeFocused()
  await input.fill('산책')
  await input.press('Enter')
  await expect(posts).toHaveCount(2)
  await page.getByRole('button', { name: '검색 초기화', exact: true }).click()
  await expect(posts).toHaveCount(5)
  await input.fill('산책')
  await input.press('Enter')
  await expect(posts).toHaveCount(2)
  await input.fill('')
  await expect(posts).toHaveCount(5)
})

test('search resets pagination and stays applied with pet filters and popularity sorting', async ({ page }, info) => {
  await signedInPreview(page)
  await mockPlayers(page)
  const reads: string[] = []
  await page.route(/\/api\/posts\?/, route => {
    const params = new URL(route.request().url()).searchParams
    const query = params.get('q') ?? ''
    const filter = params.get('filter')
    const sort = params.get('sort')
    const pageNo = Number(params.get('page'))
    reads.push(`${query}:${filter}:${sort}:${pageNo}`)
    let rows = [
      { ...samplePosts[0], id: '3', author: '최근음악', caption: '차분한 밤', tags: ['밤산책'], likes: 0 },
      { ...samplePosts[0], id: '2', author: '다른취향', petSlug: 'pip', caption: '산책하는 날', tags: [], likes: 1 },
      { ...samplePosts[0], id: '1', author: '오래된음악', caption: '오래된 이야기', tags: ['산책'], likes: 3 },
    ]
    if (query) rows = rows.filter(post => post.caption.includes(query) || post.tags.some(tag => tag.includes(query)))
    if (filter === 'same') rows = rows.filter(post => post.petSlug === 'mochi')
    if (filter === 'other') rows = rows.filter(post => post.petSlug !== 'mochi')
    if (sort === 'popular') rows.sort((a, b) => b.likes - a.likes)
    return route.fulfill({ json: { items: rows.slice(pageNo * 2, (pageNo + 1) * 2), page: pageNo, hasMore: rows.length > (pageNo + 1) * 2 } })
  })
  await page.goto('/community')
  const authors = page.locator('.post-byline strong')
  await expect(authors).toHaveText(['최근음악', '다른취향'])
  await page.getByRole('button', { name: '음악 더 보기', exact: true }).click()
  await expect(authors).toHaveCount(3)
  const input = page.getByRole('textbox', { name: '본문 또는 태그 검색' })
  await input.fill('산책')
  await input.press('Enter')
  await expect(authors).toHaveText(['최근음악', '다른취향'])
  await page.getByRole('button', { name: '음악 더 보기', exact: true }).click()
  await expect(authors).toHaveCount(3)
  await page.getByRole('button', { name: '정렬: 최신글', exact: true }).click()
  await page.getByRole('menuitem', { name: '인기글(공감순)', exact: true }).click()
  await expect(authors).toHaveText(['오래된음악', '다른취향'])
  await page.getByText('나와 같은 펫', { exact: true }).click()
  await expect(page.getByRole('radio', { name: '나와 같은 펫', exact: true })).toBeChecked()
  await expect(authors).toHaveText(['오래된음악', '최근음악'])
  await page.getByText('다른 펫', { exact: true }).click()
  await expect(page.getByRole('radio', { name: '다른 펫', exact: true })).toBeChecked()
  await expect(authors).toHaveText(['다른취향'])
  expect(reads).toEqual([':all:latest:0', ':all:latest:1', '산책:all:latest:0', '산책:all:latest:1', '산책:all:popular:0', '산책:same:popular:0', '산책:other:popular:0'])
  await page.setViewportSize({ width: 360, height: 900 })
  await expect(input).toBeVisible()
  await expect(page.getByRole('button', { name: '정렬: 인기글(공감순)', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('post-search-mobile.png') })
})
