import { expect, test } from './test'

test.beforeEach(async ({ page }) => {
  const now = new Date('2026-10-09T00:00:00Z')
  await page.clock.install({ time: now })
  await page.clock.pauseAt(now)
})

test('home examples rotate every five seconds and wrap without analysis or pet unlocks', async ({ page }, testInfo) => {
  const apiCalls: string[] = []
  page.on('request', request => {
    const path = new URL(request.url()).pathname
    if (path.startsWith('/api/') && !path.startsWith('/api/auth/')) apiCalls.push(request.url())
  })
  await page.goto('/')
  const preview = page.getByRole('region', { name: '음악 펫 결과 예시' })
  await expect(preview.getByRole('img', { name: '멜로', exact: true })).toBeVisible()
  await page.clock.runFor(4999)
  await expect(preview.getByRole('img', { name: '멜로', exact: true })).toBeVisible()
  await page.clock.runFor(1)
  await expect(preview.getByRole('img', { name: '루바', exact: true })).toBeVisible()
  await expect(preview.getByRole('group', { name: '2 / 5: 루바', exact: true })).toBeVisible()
  for (const name of ['코다', '리프', '리토', '멜로']) {
    await page.clock.runFor(5000)
    await expect(preview.getByRole('img', { name, exact: true })).toBeVisible()
  }
  expect(apiCalls).toEqual([])
  expect(await page.evaluate(() => localStorage.getItem('unlocked-characters'))).toBeNull()
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.screenshot({ path: testInfo.outputPath('home-carousel-desktop.png'), animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('home-carousel-mobile.png'), fullPage: true, animations: 'disabled' })
})

test('mouse interactions resume naturally, keyboard navigation waits for a restart, and the playback icon works on its first click', async ({ page }) => {
  await page.goto('/')
  const preview = page.getByRole('region', { name: '음악 펫 결과 예시' })
  const mochi = preview.getByRole('img', { name: '멜로', exact: true })
  await mochi.hover()
  await page.clock.runFor(10000)
  await expect(mochi).toBeVisible()
  await page.mouse.move(0, 0)
  await page.clock.runFor(5000)
  await expect(preview.getByRole('img', { name: '루바', exact: true })).toBeVisible()

  await preview.getByRole('button', { name: '다음 펫 보기' }).click()
  await expect(preview.getByRole('img', { name: '코다', exact: true })).toBeVisible()
  await expect(preview.getByRole('button', { name: '자동 전환 멈추기' })).toHaveText('')
  await page.mouse.move(0, 0)
  await page.clock.runFor(5000)
  await expect(preview.getByRole('img', { name: '리프', exact: true })).toBeVisible()

  await preview.getByRole('button', { name: '자동 전환 멈추기' }).click()
  await page.mouse.move(0, 0)
  await page.clock.runFor(10000)
  await expect(preview.getByRole('img', { name: '리프', exact: true })).toBeVisible()
  await preview.getByRole('button', { name: '자동 전환 시작하기' }).click()
  await page.mouse.move(0, 0)
  await page.clock.runFor(5000)
  await expect(preview.getByRole('img', { name: '리토', exact: true })).toBeVisible()

  await page.keyboard.press('Tab')
  await expect(preview.getByRole('button', { name: '이전 펫 보기' })).toBeFocused()
  await page.getByRole('button', { name: '이용 방법', exact: true }).focus()
  await page.clock.runFor(10000)
  await expect(preview.getByRole('img', { name: '리토', exact: true })).toBeVisible()
  await preview.getByRole('button', { name: '자동 전환 시작하기' }).focus()
  await page.keyboard.press('Enter')
  await page.clock.runFor(5000)
  await expect(preview.getByRole('img', { name: '멜로', exact: true })).toBeVisible()
})

test('reduced motion keeps examples still while arrow controls remain keyboard accessible', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  const preview = page.getByRole('region', { name: '음악 펫 결과 예시' })
  await page.clock.runFor(20000)
  await expect(preview.getByRole('img', { name: '멜로', exact: true })).toBeVisible()
  await expect(preview.getByRole('button', { name: /자동 전환/ })).toHaveCount(0)
  await preview.getByRole('button', { name: '이전 펫 보기' }).click()
  await expect(preview.getByRole('img', { name: '리토', exact: true })).toBeVisible()
  await preview.getByRole('button', { name: '다음 펫 보기' }).focus()
  await page.keyboard.press('Enter')
  await expect(preview.getByRole('img', { name: '멜로', exact: true })).toBeVisible()
  await expect(preview.getByRole('button', { name: '다음 펫 보기' })).toBeFocused()
  await page.keyboard.press('Enter')
  await page.keyboard.press('Enter')
  await expect(preview.getByRole('img', { name: '코다', exact: true })).toBeVisible()
  await expect(preview.getByRole('group', { name: '3 / 5: 코다', exact: true })).toBeVisible()
  expect(await preview.locator('.preview-pet').evaluate(element => getComputedStyle(element).animationName)).toBe('none')
  await page.clock.runFor(20000)
  await expect(preview.getByRole('img', { name: '코다', exact: true })).toBeVisible()
})
