test('player stays compact on desktop and fits mobile width', async ({ page }) => {
  await page.goto('/community')
  for (const width of [1440, 360]) {
    await page.setViewportSize({ width, height: 900 })
    const player = await page.locator('article iframe').first().boundingBox()
    const caption = await page.locator('.post-caption').first().boundingBox()
    const tags = await page.locator('.post-tags').first().boundingBox()
    expect(player!.width).toBeLessThanOrEqual(Math.min(480, width))
    expect(caption!.y).toBeGreaterThanOrEqual(player!.y + player!.height)
    expect(tags!.y).toBeGreaterThanOrEqual(caption!.y + caption!.height)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
})

test('guests can read comments but cannot change posts, comments or likes', async ({ page }) => {
  await page.goto('/community')
  const post = page.getByRole('article').first()
  await post.getByRole('button', { name: /^댓글 \d+개$/ }).click()
  await post.getByRole('textbox', { name: '댓글 입력' }).fill('누구나 읽는 댓글')
  await post.getByRole('button', { name: '댓글 등록', exact: true }).click()
  await expect(post.getByRole('paragraph').filter({ hasText: /^누구나 읽는 댓글$/ })).toBeVisible()
  await mockAuth(page, null)
  await page.reload()
  await post.getByRole('button', { name: /^댓글 \d+개$/ }).click()
  await expect(post).toContainText('누구나 읽는 댓글')
  await expect(post.getByRole('button', { name: '댓글 더보기', exact: true })).toHaveCount(0)
  await expect(post.getByRole('textbox')).toHaveCount(0)
  const before = await page.evaluate(() => localStorage.getItem('community-preview'))
  for (const name of ['답글', '공감 24']) {
    await post.getByRole('button', { name, exact: true }).click()
    await expect(page.getByRole('alertdialog')).toBeVisible()
    await page.getByRole('button', { name: '계속 둘러보기' }).click()
  }
  expect(await page.evaluate(() => localStorage.getItem('community-preview'))).toBe(before)
})

test('community OAuth return does not start an analysis', async ({ page }) => {
  let analysisCalls = 0
  await page.route('**/api/analysis', route => { analysisCalls++; return route.abort() })
  await page.goto('/login?next=/community')
  await page.evaluate(() => sessionStorage.setItem('login-destination', '/community'))
  await page.goto('/oauth/callback')
  await expect(page).toHaveURL(/\/community$/)
  await expect(page.getByRole('heading', { name: '오늘, 어떤 음악 들었어요?' })).toBeVisible()
  expect(analysisCalls).toBe(0)
  expect(await page.evaluate(() => sessionStorage.getItem('login-destination'))).toBeNull()
})

